#!/usr/bin/env python3
"""Rewrite macros_pending.tex from collected JSON. Unfilled stay \\pending{...}."""
from __future__ import annotations

import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
OUT = HERE / "macros_pending.tex"


def load(rel: str) -> dict | None:
    path = REPO / rel
    if not path.is_file():
        return None
    return json.loads(path.read_text())


def fmt(x: float, digits: int = 2) -> str:
    return f"{x:.{digits}f}"


def main() -> None:
    # Pending labels must not contain $ or other math tokens: macros are often
    # expanded inside $...$ (e.g. $\HeadlineBoundedMedian\times$).
    macros: dict[str, str] = {
        "HeadlineBoundedMedian": r"\pending{W13 headline median}",
        "HeadlineBoundedCIlow": r"\pending{W13 CI low}",
        "HeadlineBoundedCIhigh": r"\pending{W13 CI high}",
        "ReleaseChainPayback": r"\pending{W8 cumulative payback}",
        "BaselinesEpycRho": r"\pending{W5x Table 4 rho}",
        "ExpertScriptRatio": r"\pending{W12a TARE/expert ratio}",
        "ISeqSearchSpeedup": r"\pending{W12b iSeqSearch timing}",
        "PfscanTiming": r"\pending{WA2 pfscanV3 timing}",
    }

    w13 = load("pipeline/results/exact_replay/headline_bounded.json")
    if w13 and w13.get("headline_median") is not None:
        macros["HeadlineBoundedMedian"] = fmt(float(w13["headline_median"]))
        ci = w13.get("bootstrap_ci95") or {}
        if ci.get("low") is not None:
            macros["HeadlineBoundedCIlow"] = fmt(float(ci["low"]))
        if ci.get("high") is not None:
            macros["HeadlineBoundedCIhigh"] = fmt(float(ci["high"]))

    w8 = load("pipeline/results/release_chain/measured.json")
    if w8 and w8.get("cumulative_payback") is not None:
        macros["ReleaseChainPayback"] = fmt(float(w8["cumulative_payback"]))

    w5 = load("pipeline/results/baselines_x86/measured.json")
    if w5:
        # best-effort: first measured system rho
        systems = w5.get("systems") or {}
        for name, row in systems.items():
            if isinstance(row, dict) and row.get("status") == "MEASURED" and "rho" in row:
                macros["BaselinesEpycRho"] = f"{name}={fmt(float(row['rho']))}"
                break

    w12a = load("pipeline/results/baselines_exact/server.json")
    if w12a:
        summary = (w12a.get("summary") or {}).get("R_g") or {}
        if summary.get("median") is not None:
            macros["ExpertScriptRatio"] = fmt(float(summary["median"]))

    w12b = load("pipeline/results/iseqsearch_timing/measured.json")
    if w12b and w12b.get("tare_speedup") is not None:
        macros["ISeqSearchSpeedup"] = fmt(float(w12b["tare_speedup"]))

    wa = load("pipeline/results/unrelated_ship/timing_v2.json")
    if wa and wa.get("median_S_g") is not None:
        macros["PfscanTiming"] = fmt(float(wa["median_S_g"]))

    lines = [
        "% Auto-generated by fill_macros.py — do not hand-edit.",
        "% Unfilled macros use \\pending{...} so submission cannot hide them.",
        "",
    ]
    for name, value in macros.items():
        if value.startswith(r"\pending"):
            lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")
        else:
            lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")
    OUT.write_text("\n".join(lines) + "\n")
    pending = sum(1 for v in macros.values() if "pending" in v.lower() or v.startswith(r"\pending"))
    print(f"wrote {OUT} ({pending} still PENDING)")
    raise SystemExit(1 if pending else 0)


if __name__ == "__main__":
    main()
