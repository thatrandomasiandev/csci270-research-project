def _unsafe_map(path: str, order: list[str]) -> dict[str, int]:
    counts = {label: 0 for label in order}
    for row in load(path)["rows"]:
        label = row["class"]
        if label not in counts:
            if str(label).startswith("C"):
                continue
            raise SystemExit(f"unexpected class {label} in {path}")
        if row.get("unsafe_ship"):
            counts[label] += 1
    return counts


