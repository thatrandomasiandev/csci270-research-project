def _paired_fraction(name, caption, cats, series) -> None:
    # Numeric y so series can sit on parallel tracks.
    n_series = len(series)
    span = 0.46
    offsets = [span * (i - (n_series - 1) / 2) / max(n_series - 1, 1) for i in range(n_series)]
    if n_series == 1:
        offsets = [0.0]
    height = f"{1.8 + 1.05 * len(cats):.2f}cm"
    body = header(caption)
    body += "\\begin{tikzpicture}\n\\begin{axis}[\n  acts,\n"
    body += f"  width=0.92\\columnwidth,\n  height={height},\n"
    body += "  xmin=0, xmax=1.38,\n  xtick={0,0.25,0.5,0.75,1},\n"
    body += "  xlabel={Fraction of rows consistent},\n"
    body += f"  ytick={{0,...,{len(cats) - 1}}},\n"
    body += "  yticklabels={" + ",".join(f"{{{c}}}" for c in cats) + "},\n"
    body += "  y dir=reverse,\n  enlarge y limits=0.28,\n"
    body += "  legend style={at={(0.5,1.04)}, anchor=south, legend columns=2},\n"
    body += "]\n"
    body += (
        "\\addplot[draw=none, forget plot] coordinates {(0,0) (1,"
        + str(len(cats) - 1)
        + ")};\n"
    )
    for (_legend, color, _counts, _source), offset in zip(series, offsets):
        body += (
            f"\\addlegendimage{{only marks, mark=*, mark size=1.5pt, fill={color}, draw={color}}}\n"
        )
    for legend, _color, _counts, _source in series:
        body += f"\\addlegendentry{{{legend}}}\n"
    placed: list[list[tuple[float, str, str, float]]] = [[] for _ in cats]
    for (_legend, color, counts, source), offset in zip(series, offsets):
        body += f"% source: {source}\n"
        for index, (consistent, total) in enumerate(counts):
            y = index + offset
            frac = consistent / total
            placed[index].append((frac, color, f"{consistent}/{total}", y))
            body += (
                f"\\draw[{color}!35, line width=1.6pt, line cap=round] "
                f"(axis cs:0,{y:.4f}) -- (axis cs:{frac:.8g},{y:.4f});\n"
                f"\\fill[{color}] (axis cs:{frac:.8g},{y:.4f}) circle[radius=1.15pt];\n"
            )
    for items in placed:
        ordered = sorted(items)
        for j, (frac, color, text, y) in enumerate(ordered):
            nxt = ordered[j + 1][0] if j + 1 < len(ordered) else 9
            if nxt - frac < 0.16:
                body += actlab(
                    "south east", color, frac, f"{y:.4f}", text, "xshift=-1pt, yshift=1.5pt"
                )
            else:
                body += actlab("west", color, frac, f"{y:.4f}", text, "xshift=2pt")
    body += end_axis()
    write(name, body)


