def write_baselines() -> None:
    modes = load("baseline_overhead.json")["modes"]
    cats = ["Stock", "Riker", "INCR default", "INCR annotations"]
    keys = ["stock", "riker", "incr_default", "incr_annotations"]
    scan = [float(modes["hmmscan"][key]["mean_paired_ratio"]) for key in keys]
    search = [float(modes["hmmsearch"][key]["mean_paired_ratio"]) for key in keys]
    hi = max(scan + search)
    body = header(
        "First-run wall ratio versus stock. Four repeats, empty cache, new container. "
        "Not comparable to the EPYC savings node. Above 1 is slower than stock."
    )
    body += "\\begin{tikzpicture}\n\\begin{axis}[\n  acts,\n"
    body += "  width=0.92\\columnwidth,\n  height=4.4cm,\n"
    body += f"  xmin=0.85, xmax={hi * 1.28:.6g},\n"
    body += "  xlabel={Wall ratio versus stock},\n"
    body += "  ytick={0,1,2,3},\n  y dir=reverse,\n"
    body += "  yticklabels={{Stock},{Riker},{INCR default},{INCR annotations}},\n"
    body += "  enlarge y limits=0.16,\n"
    body += "  legend style={at={(0.5,1.04)}, anchor=south, legend columns=2},\n"
    body += "]\n"
    body += "\\addplot[draw=none, forget plot] coordinates {(1,0) (1,3)};\n"
    body += legend_swatch("actsteal", "actsteal", "hmmscan")
    body += legend_swatch("actsorange", "actsorange", "hmmsearch")
    body += "% source: baseline_overhead.json modes.*.mean_paired_ratio\n"
    body += "\\draw[actsrule, dashed] (axis cs:1,-0.45) -- (axis cs:1,3.45);\n"
    body += actlab("west", "actsrule", 1, "0", "1.000", "xshift=3pt")
    for index, (s_scan, s_search) in enumerate(zip(scan, search)):
        if index == 0:
            continue
        body += (
            f"\\draw[actsteal!40] (axis cs:1,{index + 0.12:.2f}) -- (axis cs:{s_scan:.8g},{index + 0.12:.2f});\n"
            f"\\fill[actsteal] (axis cs:{s_scan:.8g},{index + 0.12:.2f}) circle[radius=1.15pt];\n"
            + actlab("west", "actsteal", s_scan, f"{index + 0.12:.2f}", f"{s_scan:.3f}", "xshift=2pt")
            + f"\\draw[actsorange!45] (axis cs:1,{index - 0.12:.2f}) -- (axis cs:{s_search:.8g},{index - 0.12:.2f});\n"
            + f"\\fill[actsorange] (axis cs:{s_search:.8g},{index - 0.12:.2f}) circle[radius=1.15pt];\n"
            + actlab("west", "actsorange", s_search, f"{index - 0.12:.2f}", f"{s_search:.3f}", "xshift=2pt")
        )
    body += end_axis()
    write("fig_baseline_first_run.tex", body)


