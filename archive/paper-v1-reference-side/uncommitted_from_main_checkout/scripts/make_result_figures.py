#!/usr/bin/env python3
"""Publication figures from pipeline/results. No hand-typed coordinates.

Fig. 3 and Fig. 4 land in figures/fig3_savings.tex and fig4_residuals.tex.
Every other chart is figures/fig_*.tex, ready to \\input.
"""

from __future__ import annotations

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "results"
FIG = Path(__file__).resolve().parents[1] / "figures"

STYLE = r"\input{figures/actsplots.tex}" + "\n"


def load(name: str) -> dict:
    import json

    with (RESULTS / name).open() as handle:
        return json.load(handle)


def kx(value: float) -> str:
    return f"{float(value):.3f}\\,$\\times$"


def actlab(anchor: str, color: str, x: float, y: str, text: str, shift: str = "") -> str:
    extra = f", {shift}" if shift else ""
    return (
        f"\\node[actlab, anchor={anchor}, text={color}{extra}] "
        f"at (axis cs:{x:.8g},{y}) {{{text}}};\n"
    )


def pair_labels(
    token: str,
    left: float,
    right: float,
    left_text: str,
    right_text: str,
    left_color: str,
    right_color: str,
    xmin: float,
    xmax: float,
) -> str:
    """Place the two direct labels away from the marks.

    Arguments are series order, not spatial order. A value near the
    origin is labeled above its mark so the text stays off the y ticks.
    """
    span = max(xmax - xmin, 1e-9)
    if left <= right:
        lo_v, lo_text, lo_color = left, left_text, left_color
        hi_v, hi_text, hi_color = right, right_text, right_color
    else:
        lo_v, lo_text, lo_color = right, right_text, right_color
        hi_v, hi_text, hi_color = left, left_text, left_color
    if (lo_v - xmin) / span < 0.18:
        return (
            actlab("south", lo_color, lo_v, token, lo_text, "yshift=2pt")
            + actlab("west", hi_color, hi_v, token, hi_text, "xshift=2pt")
        )
    return (
        actlab("east", lo_color, lo_v, token, lo_text, "xshift=-2pt")
        + actlab("west", hi_color, hi_v, token, hi_text, "xshift=2pt")
    )


def header(caption: str) -> str:
    return (
        "% Generated by pipeline/paper/scripts/make_result_figures.py. "
        "Do not edit by hand.\n"
        f"% {caption}\n"
        + STYLE
    )


def write(name: str, text: str) -> None:
    (FIG / name).write_text(text)
    print(name)


def job(summary: dict, collection: str, mode: str) -> dict:
    matches = [
        item
        for item in summary["jobs"]
        if item["collection"] == collection and item["mode"] == mode
    ]
    if len(matches) != 1:
        raise SystemExit(f"expected one {collection} {mode} job, found {len(matches)}")
    return matches[0]


def sampled(job_name: str) -> list[dict]:
    rows = [
        genome
        for genome in load(f"savings_20261006/{job_name}")["genomes"]
        if genome.get("stock_pred_rel_error") is not None
    ]
    if not rows:
        raise SystemExit(f"no measured stock rows in {job_name}")
    return rows


def ytokens(labels: list[str]) -> tuple[str, str]:
    tokens = [f"r{i}" for i in range(len(labels))]
    ticks = ",".join(f"{{{label}}}" for label in labels)
    return ",".join(tokens), ticks


def _anchor_plot(tokens: str, xmin: float) -> str:
    pts = " ".join(f"({xmin:.6g},{tok})" for tok in tokens.split(","))
    return "\\addplot[draw=none, forget plot] coordinates {" + pts + "};\n"


def begin_axis(
    *,
    width: str,
    height: str,
    xlabel: str,
    tokens: str,
    ticklabels: str,
    xmin: float,
    xmax: float,
    xtick: str,
    extra: str = "",
) -> str:
    return (
        "\\begin{tikzpicture}\n\\begin{axis}[\n"
        "  acts,\n"
        f"  width={width},\n"
        f"  height={height},\n"
        f"  xmin={xmin:.6g}, xmax={xmax:.6g},\n"
        f"  xtick={{{xtick}}},\n"
        f"  xlabel={{{xlabel}}},\n"
        "  symbolic y coords={" + tokens + "},\n"
        "  ytick={" + tokens + "},\n"
        "  y dir=reverse,\n"
        "  yticklabels={" + ticklabels + "},\n"
        "  enlarge y limits=0.08,\n"
        f"{extra}"
        "]\n"
        + _anchor_plot(tokens, xmin)
    )


def end_axis() -> str:
    return "\\end{axis}\n\\end{tikzpicture}\n"


def legend_swatch(draw: str, fill: str, entry: str, *, open_mark: bool = False) -> str:
    mark = "o" if open_mark else "*"
    size = "1.7pt" if open_mark else "1.55pt"
    paint = "white" if open_mark else fill
    image = (
        "\\addlegendimage{only marks, mark="
        + mark
        + ", mark size="
        + size
        + ", draw="
        + draw
        + ", fill="
        + paint
        + "}\n"
    )
    return image + "\\addlegendentry{" + entry + "}\n"


def dumbbell_links(
    pairs: list[tuple[str, float, float]], color: str, width: str = "0.9pt"
) -> str:
    lines = [f"% connector {color}\n"]
    for token, left, right in pairs:
        lo, hi = (left, right) if left <= right else (right, left)
        lines.append(
            f"\\draw[{color}, line width={width}] "
            f"(axis cs:{lo:.8g},{token}) -- (axis cs:{hi:.8g},{token});\n"
        )
    return "".join(lines)


def marks(coords: str, color: str, source: str, *, open_mark: bool = False) -> str:
    style = (
        f"only marks, mark=o, mark size=1.8pt, draw={color}, fill=white"
        if open_mark
        else f"only marks, mark=*, mark size=1.45pt, draw={color}, fill={color}"
    )
    return (
        f"% source: {source}\n"
        f"\\addplot[{style}, forget plot] coordinates {{{coords}}};\n"
    )


def coord_list(pairs: list[tuple[float, str]]) -> str:
    return " ".join(f"({value:.8g},{token})" for value, token in pairs)


def outward_labels(
    rows: list[tuple[str, float, float, str, str]],
) -> str:
    """token, left value, right value, left label, right label."""
    chunks = []
    for token, left, right, left_label, right_label in rows:
        lo_v, hi_v = (left, right) if left <= right else (right, left)
        lo_l, hi_l = (left_label, right_label) if left <= right else (right_label, left_label)
        lo_c, hi_c = ("actsteal", "actsorange") if left <= right else ("actsorange", "actsteal")
        # Caller passes labels already colored by series, not by side.
        chunks.append(
            f"\\node[anchor=east, text={lo_c}] at (axis cs:{lo_v:.8g},{token}) {{{lo_l}}};\n"
            f"\\node[anchor=west, text={hi_c}] at (axis cs:{hi_v:.8g},{token}) {{{hi_l}}};\n"
        )
    return "".join(chunks)


def speedup_rows(summary: dict, sens: dict, mode: str) -> list[tuple[str, float, float]]:
    rows = []
    for collection, plain_name, probe_name in (
        ("A", "A, no $P$", "A, with $P$"),
        ("B", "B, no $P$", "B, with $P$"),
    ):
        cumulative = job(summary, collection, mode)["cumulative"]
        corrected = sens["collections"][collection]
        rows.append(
            (
                plain_name,
                float(corrected["cum_speedup_wall"]),
                float(cumulative["cum_speedup_wall"]),
            )
        )
        rows.append(
            (
                probe_name,
                float(corrected["cum_speedup_wall_with_P"]),
                float(cumulative["cum_speedup_wall_with_P"]),
            )
        )
    return rows


def emit_speedup(name: str, caption: str, rows: list[tuple[str, float, float]], sources: str) -> None:
    labels = [label for label, _c, _l in rows]
    tokens, ticks = ytokens(labels)
    token_of = dict(zip(labels, tokens.split(",")))
    height = f"{1.7 + 0.86 * len(rows):.2f}cm"
    hi = max(locked for _lab, _cor, locked in rows)
    xmax = hi * 1.42
    body = header(caption)
    body += begin_axis(
        width=r"0.92\columnwidth",
        height=height,
        xlabel="Cumulative wall speedup",
        tokens=tokens,
        ticklabels=ticks,
        xmin=0,
        xmax=xmax,
        xtick=_speed_ticks(hi),
        extra="  legend style={at={(0.5,1.03)}, anchor=south, legend columns=2},\n",
    )
    body += legend_swatch("actsteal", "actsteal", "Corrected")
    body += legend_swatch("actsorange", "actsorange", "Locked")
    links = [
        (token_of[label], corrected, locked)
        for label, corrected, locked in rows
    ]
    body += f"% source: {sources}\n"
    body += dumbbell_links(links, "actsorange!55")
    body += marks(
        coord_list([(c, token_of[lab]) for lab, c, _l in rows]),
        "actsteal",
        sources,
    )
    body += marks(
        coord_list([(locked, token_of[lab]) for lab, _c, locked in rows]),
        "actsorange",
        sources,
    )
    body += "% labels rounded to 2 decimals; coordinates above are full precision\n"
    for label, corrected, locked in rows:
        body += pair_labels(
            token_of[label],
            corrected,
            locked,
            kx(corrected),
            kx(locked),
            "actsteal",
            "actsorange",
            0,
            xmax,
        )
    body += end_axis()
    write(name, body)


def _speed_ticks(hi: float) -> str:
    if hi > 12:
        return "0,5,10,15,20"
    if hi > 6:
        return "0,2,4,6,8"
    return "0,1,2,3,4,5"


def write_speedups() -> None:
    summary = load("savings_summary.json")
    sens = load("savings_sensitivity.json")
    scan = load("savings_sensitivity_hmmscan.json")
    emit_speedup(
        "fig_hmmsearch_cumulative.tex",
        "hmmsearch cumulative wall speedup. Teal is the post-hoc correction. Orange is the locked imputation.",
        speedup_rows(summary, sens, "hmmsearch"),
        "savings_summary.json hmmsearch cum_speedup_wall[_with_P]; savings_sensitivity.json corrected pair",
    )
    emit_speedup(
        "fig_hmmscan_cumulative.tex",
        "POST-HOC hmmscan cumulative wall speedup. Same encoding as the hmmsearch figure.",
        speedup_rows(summary, scan, "hmmscan"),
        "savings_summary.json hmmscan cum_speedup_wall[_with_P]; savings_sensitivity_hmmscan.json corrected pair",
    )
    # Prediction vs corrected: teal = corrected, ink = prediction.
    labels = []
    pred = []
    corr = []
    for collection in ("A", "B"):
        cumulative = job(summary, collection, "hmmsearch")["cumulative"]
        block = sens["collections"][collection]
        labels += [f"{collection}, no $P$", f"{collection}, with $P$"]
        pred += [
            float(cumulative["predicted_part2_cum_speedup"]),
            float(cumulative["predicted_singleton_8_cum_speedup"]),
        ]
        corr += [
            float(block["cum_speedup_wall"]),
            float(block["cum_speedup_wall_with_P"]),
        ]
    tokens, ticks = ytokens(labels)
    token_of = dict(zip(labels, tokens.split(",")))
    hi = max(pred + corr)
    xmax = hi * 1.42
    body = header(
        "Part-2 prediction at N=4192 beside the corrected cumulative. "
        "The prediction was written before these walls."
    )
    body += begin_axis(
        width=r"0.92\columnwidth",
        height="5.2cm",
        xlabel="Cumulative wall speedup",
        tokens=tokens,
        ticklabels=ticks,
        xmin=0,
        xmax=xmax,
        xtick=_speed_ticks(hi),
        extra="  legend style={at={(0.5,1.03)}, anchor=south, legend columns=2},\n",
    )
    body += legend_swatch("actsteal", "actsteal", "Corrected")
    body += legend_swatch("actsink", "actsink", "Predicted")
    links = []
    for label, p, c in zip(labels, pred, corr):
        links.append((token_of[label], p, c))
    body += dumbbell_links(links, "black!22")
    body += marks(
        coord_list([(c, token_of[lab]) for lab, c in zip(labels, corr)]),
        "actsteal",
        "savings_sensitivity.json cum_speedup_wall and cum_speedup_wall_with_P",
    )
    body += marks(
        coord_list([(p, token_of[lab]) for lab, p in zip(labels, pred)]),
        "actsink",
        "savings_summary.json predicted_part2_cum_speedup and predicted_singleton_8_cum_speedup",
    )
    for label, p, c in zip(labels, pred, corr):
        body += pair_labels(
            token_of[label],
            c,
            p,
            kx(c),
            kx(p),
            "actsteal",
            "actsink",
            0,
            xmax,
        )
    body += end_axis()
    write("fig_hmmsearch_vs_prediction.tex", body)


def write_walls() -> None:
    for collection, job_name in (("A", "A_hmmsearch.json"), ("B", "B_hmmsearch.json")):
        rows = sampled(job_name)
        labels = [str(int(row["position"])) for row in rows]
        tokens, ticks = ytokens(labels)
        token_of = dict(zip(labels, tokens.split(",")))
        stock = [float(row["stock_wall_s"]) for row in rows]
        cached = [float(row["cached_wall_s"]) for row in rows]
        fitted = [float(row["stock_predicted_s"]) for row in rows]
        hi = max(fitted)
        body = header(
            f"Collection {collection} hmmsearch at sampled genomes. "
            "Filled marks are measured. The open mark is fitted stock a+bN."
        )
        body += begin_axis(
            width=r"0.92\columnwidth",
            height=f"{1.9 + 0.68 * len(rows):.2f}cm",
            xlabel="Wall (s)",
            tokens=tokens,
            ticklabels=ticks,
            xmin=0,
            xmax=hi * 1.08,
            xtick="0,200,400,600,800",
            extra=(
                "  legend style={at={(0.5,1.03)}, anchor=south, legend columns=3},\n"
                "  ylabel={Genome position},\n"
            ),
        )
        body += legend_swatch("actsteal", "actsteal", "Cached")
        body += legend_swatch("actsink", "actsink", "Stock")
        body += legend_swatch("actsghost", "white", "Fitted", open_mark=True)
        links = [
            (token_of[label], c, s) for label, c, s in zip(labels, cached, stock)
        ]
        ghost = [
            (token_of[label], s, f) for label, s, f in zip(labels, stock, fitted)
        ]
        body += dumbbell_links(links, "black!25")
        body += dumbbell_links(ghost, "actsghost, dashed", "0.55pt")
        src = f"savings_20261006/{job_name}"
        body += marks(
            coord_list([(c, token_of[lab]) for lab, c in zip(labels, cached)]),
            "actsteal",
            f"{src} cached_wall_s where stock_pred_rel_error is set",
        )
        body += marks(
            coord_list([(s, token_of[lab]) for lab, s in zip(labels, stock)]),
            "actsink",
            f"{src} stock_wall_s",
        )
        body += marks(
            coord_list([(f, token_of[lab]) for lab, f in zip(labels, fitted)]),
            "actsghost",
            f"{src} stock_predicted_s",
            open_mark=True,
        )
        body += end_axis()
        write(f"fig_hmmsearch_walls_{collection}.tex", body)


def write_fit_error() -> None:
    rows = sampled("A_hmmsearch.json") + sampled("B_hmmsearch.json")
    labels = [f"{'A' if i < 6 else 'B'}{int(row['position'])}" for i, row in enumerate(rows)]
    # A file is first and has 6 sampled rows. Don't assume 6 if the file changes.
    a_n = len(sampled("A_hmmsearch.json"))
    labels = [
        f"A{int(row['position'])}" for row in rows[:a_n]
    ] + [f"B{int(row['position'])}" for row in rows[a_n:]]
    values = [float(row["stock_pred_rel_error"]) for row in rows]
    tokens, ticks = ytokens(labels)
    token_of = dict(zip(labels, tokens.split(",")))
    hi = max(values)
    body = header(
        "Relative error of fitted stock on every sampled genome. "
        "The band is the 0.10 flag. Every genome is outside it."
    )
    body += begin_axis(
        width=r"0.92\columnwidth",
        height="6.6cm",
        xlabel="Relative fit error",
        tokens=tokens,
        ticklabels=ticks,
        xmin=0,
        xmax=hi * 1.28,
        xtick="0,0.2,0.4,0.6,0.8",
        extra="  ylabel={Sampled genome},\n",
    )
    body += (
        "% source: locked flag |predicted-measured|/measured > 0.10\n"
        f"\\fill[actstealfaint] (axis cs:0,{token_of[labels[0]]}) "
        f"rectangle (axis cs:0.1,{token_of[labels[-1]]});\n"
        "\\node[actlab, anchor=south west, text=actsteal, yshift=1pt] at (axis cs:0.012,"
        f"{token_of[labels[0]]}) {{within 0.10}};\n"
    )
    for label, value in zip(labels, values):
        token = token_of[label]
        body += (
            f"\\draw[actsfail!75, line width=0.7pt] (axis cs:0.1,{token}) -- (axis cs:{value:.8g},{token});\n"
            f"\\fill[actsfail] (axis cs:{value:.8g},{token}) circle[radius=1.15pt];\n"
            + actlab("west", "actsfail", value, token, f"{value:.2f}", "xshift=1.5pt")
        )
    body += (
        "% source: savings_20261006/A_hmmsearch.json and B_hmmsearch.json stock_pred_rel_error\n"
    )
    body += end_axis()
    write("fig_hmmsearch_fit_error.tex", body)


def write_savings() -> None:
    """Fig. 3: measured walls, then the corrected-vs-locked gap. hmmsearch only."""
    summary = load("savings_summary.json")
    sens = load("savings_sensitivity.json")
    a_rows = sampled("A_hmmsearch.json")
    b_rows = sampled("B_hmmsearch.json")
    genomes = [("A" + str(int(row["position"])), row) for row in a_rows] + [
        ("B" + str(int(row["position"])), row) for row in b_rows
    ]
    labels = [label for label, _row in genomes]
    tokens, ticks = ytokens(labels)
    token_of = dict(zip(labels, tokens.split(",")))
    fitted_hi = max(float(row["stock_predicted_s"]) for _l, row in genomes)
    speed = speedup_rows(summary, sens, "hmmsearch")
    slabels = [label for label, _c, _l in speed]
    stokens, sticks = ytokens(slabels)
    stoken = dict(zip(slabels, stokens.split(",")))
    speed_hi = max(locked for _l, _c, locked in speed)

    body = header(
        "Fig. 3. Left: measured cached and stock wall; open mark is fitted stock. "
        "Right: hmmsearch cumulative speedup, corrected (teal) to locked (orange)."
    )
    body += "\\begin{tikzpicture}\n\\begin{groupplot}[\n"
    body += "  group style={group size=2 by 1, horizontal sep=14mm},\n"
    body += "  acts,\n  width=0.40\\textwidth,\n  height=7.15cm,\n"
    body += "]\n\\nextgroupplot[\n"
    body += "  xmin=0, xmax=820,\n  xtick={0,200,400,600,800},\n"
    body += "  xlabel={Wall (s)},\n  ylabel={Sampled genome},\n"
    body += f"  symbolic y coords={{{tokens}}},\n  ytick=data,\n  y dir=reverse,\n"
    body += f"  yticklabels={{{ticks}}},\n  enlarge y limits=0.04,\n"
    body += "  legend style={at={(0.5,1.04)}, anchor=south, legend columns=3},\n"
    body += "]\n"
    body += legend_swatch("actsteal", "actsteal", "Cached")
    body += legend_swatch("actsink", "actsink", "Stock")
    body += legend_swatch("actsghost", "white", "Fitted $a{+}bN$", open_mark=True)
    links = []
    ghosts = []
    cached_c, stock_c, fit_c = [], [], []
    for label, row in genomes:
        token = token_of[label]
        cached = float(row["cached_wall_s"])
        stock = float(row["stock_wall_s"])
        fitted = float(row["stock_predicted_s"])
        links.append((token, cached, stock))
        ghosts.append((token, stock, fitted))
        cached_c.append((cached, token))
        stock_c.append((stock, token))
        fit_c.append((fitted, token))
    body += "% source: savings_20261006/{A,B}_hmmsearch.json sampled genomes\n"
    body += dumbbell_links(links, "black!25")
    body += dumbbell_links(ghosts, "actsghost, dashed", "0.55pt")
    body += marks(coord_list(cached_c), "actsteal", "cached_wall_s")
    body += marks(coord_list(stock_c), "actsink", "stock_wall_s")
    body += marks(coord_list(fit_c), "actsghost", "stock_predicted_s", open_mark=True)
    if fitted_hi > 820:
        raise SystemExit(f"fitted stock {fitted_hi} exceeds fig3 xmax 820")

    speed_xmax = speed_hi * 1.48
    body += "\\nextgroupplot[\n"
    body += f"  xmin=0, xmax={speed_xmax:.6g},\n  xtick={{0,2,4,6,8}},\n"
    body += "  xlabel={Cumulative wall speedup},\n"
    body += f"  symbolic y coords={{{stokens}}},\n  ytick=data,\n  y dir=reverse,\n"
    body += f"  yticklabels={{{sticks}}},\n  enlarge y limits=0.16,\n"
    body += "  legend style={at={(0.5,1.06)}, anchor=south, legend columns=2},\n"
    body += "]\n"
    body += legend_swatch("actsteal", "actsteal", "Corrected")
    body += legend_swatch("actsorange", "actsorange", "Locked")
    slinks = [
        (stoken[label], corrected, locked) for label, corrected, locked in speed
    ]
    body += (
        "% source: savings_sensitivity.json corrected; "
        "savings_summary.json hmmsearch locked cumulative\n"
    )
    body += dumbbell_links(slinks, "actsorange!55")
    body += marks(
        coord_list([(c, stoken[lab]) for lab, c, _l in speed]),
        "actsteal",
        "savings_sensitivity.json",
    )
    body += marks(
        coord_list([(locked, stoken[lab]) for lab, _c, locked in speed]),
        "actsorange",
        "savings_summary.json hmmsearch",
    )
    for label, corrected, locked in speed:
        body += pair_labels(
            stoken[label],
            corrected,
            locked,
            kx(corrected),
            kx(locked),
            "actsteal",
            "actsorange",
            0,
            speed_xmax,
        )
    body += "\\end{groupplot}\n\\end{tikzpicture}\n"
    write("fig3_savings.tex", body)


def sci(value: float) -> str:
    value = float(value)
    if value >= 0.01:
        return f"${value:.3f}$"
    exponent = math.floor(math.log10(value))
    mantissa = value / 10**exponent
    return f"${mantissa:.2f}\\times 10^{{{exponent}}}$"


def write_residuals() -> None:
    block = load("reference_fitter_t1.json")["tie_break_residuals"]["r2p"]["tblout"]
    entry = [float(block[col]["tie_break"]["entry_count"]["max_abs_residual"]) for col in ("4", "7")]
    length = [
        float(block[col]["tie_break"]["total_entry_length"]["max_abs_residual"]) for col in ("4", "7")
    ]
    rows = [
        ("4, entry count", entry[0], "actsteal"),
        ("4, total length", length[0], "actsorange"),
        ("7, entry count", entry[1], "actsteal"),
        ("7, total length", length[1], "actsorange"),
    ]
    labels = [label for label, _v, _c in rows]
    tokens, ticks = ytokens(labels)
    token_of = dict(zip(labels, tokens.split(",")))
    body = header(
        "Fig. 4. Maximum absolute residual on the R2p tie-break. Log scale. "
        "Teal is entry count. Orange is total entry length."
    )
    body += "\\begin{tikzpicture}\n\\begin{axis}[\n  acts,\n"
